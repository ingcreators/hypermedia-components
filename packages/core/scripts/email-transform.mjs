// Pure email-template transformer for @hypermedia-components/core.
//
// No Node.js dependencies — safe to import in a browser bundle (the docs
// theme builder's Email tab) and from the CLI's `email eject`. Token
// resolution itself lives in token-transform.mjs (`resolveTokens`); this
// module turns fragment sources + resolved token maps into the shippable
// email files.
//
// Fragment sources (src/email/<name>/fragment.html) are Thymeleaf
// natural templates whose inline styles reference tokens by their FLAT
// names — the `--hc-*` names minus the prefix — wrapped in braces:
//
//   style="background-color:{button-primary-bg};"
//
// `{name.dark}` (used only by the styles partial) reads the dark map.
// CSS rule bodies never collide with this shape: every CSS declaration
// contains a `:` and the placeholder pattern excludes it. Thymeleaf
// expressions (`${title}`) are excluded by the `$` lookbehind.

import { parseOklch, oklchToHex } from './oklch.mjs';

const PLACEHOLDER_RE = /(?<!\$)\{([a-z0-9][a-z0-9-]*)(\.dark)?\}/g;

// rem -> px at the 16px root size. Email clients that matter (Outlook's
// Word engine, several webmail contexts) don't resolve rem; the token
// sources are rem-based, so every substituted value is converted.
function pxify(value) {
  return value.replace(/(\d*\.?\d+)rem\b/g, (_, n) => `${Math.round(parseFloat(n) * 16)}px`);
}

// oklch() -> #rrggbb, including inside composite values (color-mix,
// borders, shadows). Same reasoning as pxify: the design primitives are
// authored in OKLCH, but the email render target is the one place custom
// properties — and modern colour spaces — cannot be assumed. Outlook's
// Word engine parses hex and little else, so every substituted colour is
// converted to the sRGB literal it rasterizes to.
const OKLCH_RE = /oklch\(\s*[\d.]+%?\s+[\d.]+\s+[\d.]+\s*\)/g;
function hexify(value) {
  return value.replace(OKLCH_RE, (m) => {
    const parsed = parseOklch(m);
    return parsed ? oklchToHex(parsed) : m;
  });
}

/**
 * Normalize one resolved token value for the email render target:
 * rem -> px, oklch() -> #rrggbb. Exported so consumers comparing
 * against the baked output (tests, the builder preview) can apply the
 * same mapping to a raw resolved value.
 */
export const emailSafeValue = (value) => hexify(pxify(value));

/**
 * Replace `{flat-token-name}` / `{flat-token-name.dark}` placeholders
 * with resolved literal values (rem converted to px). Throws on a
 * placeholder that matches neither map — typos must fail generation,
 * not ship half-themed email.
 *
 * @param {string} source fragment source HTML
 * @param {{tokens: Map<string,string>, darkTokens?: Map<string,string>}} maps
 */
export function expandEmailHtml(source, { tokens, darkTokens }) {
  return source.replace(PLACEHOLDER_RE, (m, name, dark) => {
    const value = (dark ? darkTokens : tokens)?.get(name);
    if (value == null) throw new Error(`Unknown email token reference: ${m}`);
    return emailSafeValue(value);
  });
}

/**
 * Strip `th:*` / `xmlns:th` attributes for the engine-neutral plain
 * flavor. Sources are hc-authored under the guard test's rules
 * (attribute values never contain `"` or `>`, attributes are separated
 * by exactly one space), so the attribute-shaped scan is exact for
 * them. Single `\s` (not `\s+`) keeps the scan linear on
 * whitespace-heavy inputs — the transformer also runs in the browser
 * (CodeQL js/polynomial-redos).
 */
export function stripThymeleaf(html) {
  return html.replace(/\s(?:th|xmlns):[a-z-]+="[^"]*"/g, '');
}

// User-facing fragments, in the order they appear in hc-email.html.
export const EMAIL_FRAGMENTS = [
  'button', 'heading', 'text', 'link', 'separator',
  'badge', 'alert', 'panel', 'table', 'footer',
];
// Structural sources consumed by buildEmailFiles itself.
export const EMAIL_PARTIALS = ['layout', 'styles'];

/**
 * Ordered layer stacks (namespace lists) for one axis combination, in
 * the shape `resolveTokens` expects. Dark appends `theme.dark` and the
 * ramp's dark surfaces, matching DEFAULT_SOURCES overlay order.
 */
export function emailLayerStacks({ color = 'default', neutral = 'gray' } = {}) {
  const light = ['primitive', 'semantic', 'component', 'density.comfortable', 'color.default'];
  if (color !== 'default') light.push(`color.${color}`);
  if (neutral !== 'gray') light.push(`neutral.${neutral}`);
  const dark = [...light, 'theme.dark'];
  if (neutral !== 'gray') dark.push(`neutral.${neutral}.dark`);
  return { light, dark };
}

/**
 * Reproducibility header prepended to every generated file: what
 * produced it and the exact command that regenerates it.
 */
export function emailManifestComment({ version, color, neutral, flavor, custom = false, command }) {
  return (
    '<!--\n' +
    `  Generated by @hypermedia-components/core ${version} email-transform.\n` +
    `  Axes: color=${color} neutral=${neutral} flavor=${flavor}` +
    (custom ? ' (+ custom token overrides)' : '') + '\n' +
    `  Regenerate: ${command}\n` +
    '  Do not edit by hand - edit your theme and regenerate.\n' +
    '-->\n'
  );
}

/** The runtime-theming escape hatch: both resolved maps as JSON. */
export function emailTokensJson(tokens, darkTokens) {
  // The machine contract gets the same email-safe values the templates
  // bake — consumers assembling their own emails from this map face the
  // same client limitations the fragments do.
  const safe = (map) => Object.fromEntries([...map].map(([k, v]) => [k, emailSafeValue(v)]));
  return (
    JSON.stringify({ light: safe(tokens), dark: safe(darkTokens) }, null, 2) + '\n'
  );
}

/**
 * Assemble the shippable files from fragment sources.
 *
 * @param {Object} opts
 * @param {Record<string, string>} opts.fragmentSources sources by name,
 *   including the 'layout' and 'styles' partials
 * @param {Map<string,string>} opts.tokens light map (resolveTokens)
 * @param {Map<string,string>} opts.darkTokens dark map
 * @param {'thymeleaf'|'plain'} [opts.flavor]
 * @param {string} [opts.manifest] header comment (emailManifestComment)
 * @returns {Record<string, string>} generated files by file name
 */
export function buildEmailFiles({ fragmentSources, tokens, darkTokens, flavor = 'thymeleaf', manifest = '' }) {
  const expand = (src) => {
    let out = expandEmailHtml(src, { tokens, darkTokens });
    if (flavor === 'plain') out = stripThymeleaf(out);
    return out;
  };
  const styles = expand(fragmentSources.styles).trim();
  const layout = expand(fragmentSources.layout).replace('<!--hc:styles-->', styles);
  const parts = EMAIL_FRAGMENTS.filter((n) => fragmentSources[n] != null).map(
    (n) => `<!-- hc-email fragment: ${n} -->\n${expand(fragmentSources[n]).trim()}\n`
  );
  return {
    'hc-email-layout.html': manifest + layout,
    'hc-email.html': manifest + parts.join('\n'),
  };
}
